static inline const glyph *glyph_of(char ch)
{
	ch = (char)toupper((unsigned char)ch);
	for (size_t index = 0; index < sizeof(font) / sizeof(font[0]); index++)
		if (font[index].ch == ch)
			return &font[index];
	return NULL;    /* (a space, or a sign it has not: left blank) */
}

